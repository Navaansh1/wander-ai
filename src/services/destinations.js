// In-Memory cache for dynamically resolved Wikipedia photos
const dynamicImageCache = new Map();

/**
 * Returns a high-resolution natural travel photo matching the destination query.
 * Checks local fast dictionary first, then falls back to default.
 */
export function getDestinationBackground(query) {
  if (!query || typeof query !== 'string') return DESTINATION_BACKGROUNDS.default;

  const normalized = query.toLowerCase().replace(/[^a-z0-9]/g, '');

  // Check in-memory cache first
  if (dynamicImageCache.has(normalized)) {
    return dynamicImageCache.get(normalized);
  }

  // Look for direct key match or substring containment in curated presets
  for (const [cityKey, imageUrl] of Object.entries(DESTINATION_BACKGROUNDS)) {
    if (cityKey === 'default') continue;
    if (normalized.includes(cityKey)) {
      return imageUrl;
    }
  }

  return DESTINATION_BACKGROUNDS.default;
}

/**
 * Dynamically fetches high-resolution Wikipedia / Wikimedia Commons landmark photo
 * for ANY city or country in the world that is not in the curated dictionary.
 */
export async function resolveAnyDestinationImage(query) {
  if (!query || typeof query !== 'string' || !query.trim()) {
    return DESTINATION_BACKGROUNDS.default;
  }

  const normalized = query.toLowerCase().replace(/[^a-z0-9]/g, '');

  // 1. Return from curated presets if present
  for (const [cityKey, imageUrl] of Object.entries(DESTINATION_BACKGROUNDS)) {
    if (cityKey === 'default') continue;
    if (normalized.includes(cityKey)) {
      return imageUrl;
    }
  }

  // 2. Check cache
  if (dynamicImageCache.has(normalized)) {
    return dynamicImageCache.get(normalized);
  }

  // 3. Extract primary city name from comma separated inputs (e.g. "Amritsar, Punjab" -> "Amritsar")
  const primaryTerm = query.split(',')[0].trim();

  try {
    const endpoint = `https://en.wikipedia.org/w/api.php?action=query&titles=${encodeURIComponent(primaryTerm)}&prop=pageimages&format=json&pithumbsize=1920&origin=*`;
    const res = await fetch(endpoint);
    const data = await res.json();

    if (data?.query?.pages) {
      const page = Object.values(data.query.pages)[0];
      if (page?.thumbnail?.source) {
        const url = page.thumbnail.source;
        dynamicImageCache.set(normalized, url);
        return url;
      }
    }
  } catch (err) {
    console.warn('Dynamic image search fallback to default:', err.message);
  }

  return DESTINATION_BACKGROUNDS.default;
}

