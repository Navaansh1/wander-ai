/**
 * Returns dynamic color tokens that harmonize with the background photo palette.
 */
export function getDestinationTheme(query) {
  if (!query || typeof query !== 'string') return DESTINATION_THEMES.sunset;
  const q = query.toLowerCase();

  // Tropical (emerald / teal / cyan)
  if (/bali|maldives|goa|hawaii|phuket|thailand|kerala|cancun|caribbean|island|beach/.test(q)) {
    return DESTINATION_THEMES.tropical;
  }

  // Sakura / Blossom (rose / pink / coral)
  if (/kyoto|tokyo|japan|seoul|korea|osaka|hiroshima/.test(q)) {
    return DESTINATION_THEMES.sakura;
  }

  // Alpine / Winter (glacier sky blue / cyan / indigo)
  if (/swiss|alps|switzerland|iceland|manali|kashmir|norway|finland|ladakh|shimla|mountain/.test(q)) {
    return DESTINATION_THEMES.alpine;
  }

  // Default warm golden sunset (Cappadocia, Paris, Rome, Dubai, etc.)
  return DESTINATION_THEMES.sunset;
}
